"""
End-to-end evaluation on synthetic document images (generated by synthetic_docs.py).

    python scripts/evaluate_pipeline.py --data data/synthetic --split test --limit 300

Reports: document-type accuracy + confusion, and per-entity VALUE recall
(the exact value must be recovered, e.g. all 14 digits of the national ID).
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from legacylens_ai.pii.egypt_recognizers import normalize_digits  # noqa: E402
from legacylens_ai.pipeline import analyzer, scan  # noqa: E402

VALUE_ENTITIES = {"EG_NATIONAL_ID", "EG_IBAN", "EG_MOBILE", "PASSPORT_NUMBER"}


def norm(v: str) -> str:
    return normalize_digits(v).replace(" ", "").upper()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="data/synthetic")
    ap.add_argument("--split", default="test")
    ap.add_argument("--limit", type=int, default=300)
    ap.add_argument("--out", default="reports/pipeline_eval.json")
    a = ap.parse_args()

    rows = [json.loads(line) for line in open(Path(a.data) / "labels.jsonl", encoding="utf-8")]
    rows = [r for r in rows if r["split"] == a.split][: a.limit]
    confusion, hit, total = Counter(), defaultdict(int), defaultdict(int)
    by_aug = defaultdict(lambda: [0, 0])
    import legacylens_ai.pipeline as pl
    for i, r in enumerate(rows):
        data = (Path(a.data) / r["file"]).read_bytes()
        # need raw values to compare -> run analyzer through the pipeline's internals
        captured = {}
        orig = pl.analyzer().analyze
        def spy(text, _orig=orig):
            res = _orig(text)
            captured.setdefault("values", []).extend(res)
            return res
        pl.analyzer().analyze = spy
        rep = scan(data, Path(r["file"]).name)
        pl.analyzer().analyze = orig
        pred = rep["document_type"]["label"]
        confusion[(r["class"], pred)] += 1
        found = {(f.entity, norm(f.text)) for f in captured.get("values", [])}
        for p in r["pii"]:
            if p["entity"] in VALUE_ENTITIES:
                total[p["entity"]] += 1
                ok = (p["entity"], norm(p["text"])) in found
                hit[p["entity"]] += ok
                by_aug[(p["entity"], r["augmented"])][0] += ok
                by_aug[(p["entity"], r["augmented"])][1] += 1
        if (i + 1) % 25 == 0:
            print(f"  {i + 1}/{len(rows)}")

    classes = sorted({c for c, _ in confusion} | {p for _, p in confusion})
    acc = sum(v for (c, p), v in confusion.items() if c == p) / max(1, sum(confusion.values()))
    print(f"\nDocument type accuracy: {acc:.3f}  (n={sum(confusion.values())})")
    print("confusion (rows=true, cols=pred):")
    print(" " * 11 + "".join(f"{c[:9]:>10}" for c in classes))
    for c in classes:
        print(f"{c[:10]:<11}" + "".join(f"{confusion[(c, p)]:>10}" for p in classes))
    print("\nValue recall (exact value recovered):")
    report = {"doc_type_accuracy": acc, "value_recall": {}}
    for e in sorted(total):
        clean, aug = by_aug[(e, False)], by_aug[(e, True)]
        rec = hit[e] / total[e]
        report["value_recall"][e] = {"all": rec, "clean": clean[0] / max(1, clean[1]), "augmented": aug[0] / max(1, aug[1]), "n": total[e]}
        print(f"  {e:<16} all={rec:.2f}  clean={clean[0]}/{clean[1]}  augmented={aug[0]}/{aug[1]}")
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(report, indent=2))
    print(f"saved -> {a.out}")


if __name__ == "__main__":
    main()
